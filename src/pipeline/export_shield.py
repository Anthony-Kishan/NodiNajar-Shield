"""
Climate Shield outputs for the web app, the API, the MCP server and the assistant.

    python -m src.pipeline.export_web        # (if NISAR results changed)
    python -m src.pipeline.scorecard         # forecast.json, scorecard.json
    python tools/fetch_outlook.py            # optional: GloFAS + GFS (no account needed)
    python tools/fetch_osm_assets.py         # optional: schools, mosques, markets from OpenStreetMap
    python -m src.pipeline.export_shield     # hazard.json, exposure.json, outlook.json, priorities.json

Every number written here comes from src/compute (tested). Nothing is generated by a language model.
"""
from __future__ import annotations

import argparse
import json
from datetime import date
from pathlib import Path

from src.compute import exposure as ex
from src.compute import hazard as hz
from src.compute import outlook as ol
from src.compute import planner as pl

ROOT = Path(__file__).resolve().parents[2]
HORIZON = 2  # index of the forecast target used for the exposure zone (third pass = 36 days)


def _load(p: Path):
    return json.loads(p.read_text()) if p.exists() else None


def build_outlook(raw: dict) -> dict:
    today = raw["fetched_utc"][:10]
    gauges = []
    for g in raw["gauges"]:
        o = ol.outlook(g["series"], {d: q for d, q in g["history"].items()}, today)
        gauges.append({"name": g["name"], "lat": g["lat"], "lon": g["lon"], **o})
    main = gauges[0]
    return {
        "source": "Copernicus Emergency Management Service GloFAS v4 river discharge (via Open-Meteo Flood API); "
                  "NOAA GFS precipitation (via Open-Meteo)",
        "fetched_utc": raw["fetched_utc"], "gauges": gauges,
        "river": {"trend": main["trend_7d"]["trend"], "band": main["today"]["band"], "gauge": main["name"]},
        "basin_rain": {"days": raw.get("rain_days"), **ol.basin_rain(raw.get("rain_points", [])),
                       "points": raw.get("rain_points", [])},
        "status": "MODEL FORECAST",
    }


def main(argv: list[str] | None = None) -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--data", default=str(ROOT / "webapp" / "public" / "data"))
    ap.add_argument("--raw", default=str(ROOT / "data"))
    ap.add_argument("--crews", type=int, default=5)
    ap.add_argument("--shelter", type=int, default=500)
    a = ap.parse_args(argv)
    data, raw = Path(a.data), Path(a.raw)

    man = _load(data / "manifest.json")
    segs = _load(data / "segments.geojson")["features"]
    homes = [f["geometry"]["coordinates"] for f in _load(data / "homes.geojson")["features"]]
    banks = (_load(data / "banklines.geojson") or {"features": []})["features"]
    fc = {r["id"]: r["forecast"] for r in _load(data / "forecast.json")["stretches"]}
    rain_file = _load(data / "rain.json")
    assets = (_load(raw / "osm_assets.json") or {}).get("assets", [])

    dates = [p["date"] for p in man["passes"]]
    water = [p["water_km2"] for p in man["passes"]]
    rain_by = {r["date"]: r["rain_window_mm"] for r in (rain_file or {}).get("by_pass", [])}
    rain = [rain_by.get(d) for d in dates]
    stretches = [f["properties"] for f in segs]

    # ---- river outlook (optional) ----
    outlook = None
    if (raw / "outlook_raw.json").exists():
        outlook = build_outlook(_load(raw / "outlook_raw.json"))
        (data / "outlook.json").write_text(json.dumps(outlook))
        print(f"outlook: {outlook['river']}")
    else:
        print("outlook: data/outlook_raw.json missing; run python tools/fetch_outlook.py")

    # ---- ML hazard ----
    hazard = hz.train_and_predict(stretches, dates, water, rain)
    hazard["status"] = "PROVISIONAL"
    (data / "hazard.json").write_text(json.dumps(hazard))
    bt = hazard["backtest"]
    print(f"hazard: model {hazard['model']}, rows {hazard['n_rows']}, base rate {hazard['base_rate']}, "
          f"best in back-test {bt['best']}: " + ", ".join(f"{k} brier {v['brier']} auc {v['auc']}" for k, v in bt['models'].items()))

    # ---- exposure ----
    last = len(dates) - 1
    exp_rows = {}
    for f in segs:
        p = f["properties"]
        lines = [b["geometry"]["coordinates"] for b in banks
                 if b["properties"]["pass"] == last and b["properties"]["side"] == p["side"]]
        fco = fc.get(p["id"]) or {}
        t = (fco.get("targets") or [None] * (HORIZON + 1))[HORIZON] if fco.get("ok") else None
        adv_exp = t["advance_m"] if t else None
        adv_high = max(t["high_m"] - fco["last_measured"]["position_m"], 0.0) if t else None
        e = ex.stretch_exposure(f["geometry"]["coordinates"][0], homes, lines, adv_exp, adv_high, assets)
        exp_rows[p["id"]] = {"id": p["id"], "advance_expected_m": adv_exp,
                             "advance_high_m": None if adv_high is None else round(adv_high, 1), **e}
    exposure = {
        "household_size": ex.HOUSEHOLD_SIZE,
        "household_source": "Bangladesh Population and Housing Census 2022 (BBS), national average",
        "horizon": (fc[next(iter(fc))].get("targets") or [{}] * 3)[HORIZON].get("date") if fc else None,
        "assets_source": "OpenStreetMap contributors" if assets else None,
        "stretches": list(exp_rows.values()),
        "totals": {k: sum(r[k] for r in exp_rows.values()) for k in
                   ("homes", "people_est", "homes_in_high_zone", "people_in_high_zone_est")},
    }
    (data / "exposure.json").write_text(json.dumps(exposure))

    # ---- priorities + default plan ----
    scen = "river_rising" if outlook and outlook["river"]["trend"] == "rising" else "river_not_rising"
    pri = []
    for h in hazard["stretches"]:
        e = exp_rows[h["id"]]
        p = (h["scenarios"] or {}).get(scen, {}).get("p", 0.0) if h["scenarios"] else 0.0
        esc = ol.escalate(h["level"], outlook["river"]["trend"] if outlook else "unknown",
                          outlook["river"]["band"] if outlook else "unknown")
        pri.append({"id": h["id"], "level": h["level"], "p": p, **esc,
                    "people_est": e["people_est"], "people_in_high_zone_est": e["people_in_high_zone_est"]})
    plan = pl.plan(pri, a.crews, a.shelter)
    priorities = {"scenario": scen, "scenario_from": "river outlook" if outlook else "default (no outlook fetched)",
                  "generated": date.today().isoformat(), "stretches": pri, "default_plan": plan}
    (data / "priorities.json").write_text(json.dumps(priorities))
    t = exposure["totals"]
    print(f"exposure: {t}; plan ({a.crews} crews, {a.shelter} places) covers {plan['expected_people_covered']} "
          f"of {plan['expected_people_total']} expected people")


if __name__ == "__main__":
    main()
